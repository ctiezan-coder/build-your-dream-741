// Search function to find HS codes by code or description
export function searchHSCodes(query: string, limit = 20): HSCode[] {
  if (!query || query.length < 2) return [];
  
  const normalizedQuery = query.toLowerCase().trim();
  
  return HS_CODES
    .filter(hs => 
      hs.code.includes(normalizedQuery) || 
      hs.description.toLowerCase().includes(normalizedQuery)
    )
    .slice(0, limit);
}

// Get HS code by exact code
export function getHSCode(code: string): HSCode | undefined {
  return HS_CODES.find(hs => hs.code === code);
}

// Get customs duty rate for a given HS code
export function getCustomsDutyRateFromHSCode(code: string): number {
  const hsCode = getHSCode(code);
  return hsCode ? hsCode.dutyRate / 100 : 0.08; // Default 8% if not found
}
